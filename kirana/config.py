"""Application metadata. Override the version with APP_VERSION in .env."""
import os

from .constants import (
    DEFAULT_APP_NAME,
    DEFAULT_DEVELOPER_CONTACT,
    DEFAULT_DEVELOPER_LOCATION,
    DEFAULT_DEVELOPER_NAME,
    DEFAULT_LICENSE,
    DEFAULT_VERSION,
)

APP_NAME = os.getenv("APP_NAME", DEFAULT_APP_NAME)
DEVELOPER_NAME = os.getenv("DEVELOPER_NAME", DEFAULT_DEVELOPER_NAME)
DEVELOPER_CONTACT = os.getenv("DEVELOPER_CONTACT", DEFAULT_DEVELOPER_CONTACT)
DEVELOPER_LOCATION = os.getenv("DEVELOPER_LOCATION", DEFAULT_DEVELOPER_LOCATION)
APP_LICENSE = os.getenv("APP_LICENSE", DEFAULT_LICENSE)


def app_version():
    return (os.getenv("APP_VERSION") or DEFAULT_VERSION).strip() or DEFAULT_VERSION
